FastMathClass::Table FastMathClass::GenerateTable() {
  Table c;
  for (int i = 0; i < (1 << kBits); i++) {
    c.log[i] = log(1.0 + static_cast<float>(i) / (1 << kBits)) / log(2.0);
    c.log_diff[i] =
        (log(1.0 + static_cast<float>(i + 1) / (1 << kBits)) / log(2.0) -
         c.log[i]) /
        (1 << (23 - kBits));

    c.exp1[i] = static_cast<int>(
        (std::pow(2.0F, static_cast<float>(i) / (1 << kBits)) - 1) * (1 << 23));
  }
  for (int i = 0; i < (1 << (15 - kBits)); i++) {
    c.exp2[i] = std::pow(2.0F, static_cast<float>(i) / (1 << 15));
  }
  return c;
}

FastMathDClass::Table FastMathDClass::GenerateTable() {
  Table c;
  for (int i = 0; i < (1 << kBits); i++) {
    c.log[i] = log(1.0 + static_cast<double>(i) / (1 << kBits)) / log(2.0);
    c.log_diff1[i] =
        (log(1.0 + static_cast<double>(i + 1) / (1 << kBits)) / log(2.0) -
         c.log[i]) *
        pow(2.0, kBits - 20);

    c.log_diff2[i] =
        (log(1.0 + static_cast<double>(i + 1) / (1 << kBits)) / log(2.0) -
         c.log[i]) *
        pow(2.0, kBits - 51);

    c.exp1[i] = static_cast<int>(
        (pow(2.0, static_cast<double>(i) / (1 << kBits)) - 1) * (1 << 20));
    c.exp2[i] = pow(2.0, static_cast<double>(i) / (1 << kBits));
  }
  c.magic = (pow(2.0, pow(2.0, -kBits)) - 1) * pow(2.0, -31);
  return c;
}

double FastMathDClass::FastLog2(double d) const {
  assert(d > 0);
  const int64_t x = absl::bit_cast<int64_t>(d);
  const int32_t x_low = x;
  const int32_t x_high = x >> 32;
  const uint32_t y = x_high >> (20 - kBits) & kMask1;
  const int32_t exponent = static_cast<int32_t>((x_high >> 20) & 0x7FF) - 1023;
  return exponent + cache_.log[y] + (x_high & kMask2) * cache_.log_diff1[y] +
         ((x_low >> 1) & 0x7FFFFFFF) * cache_.log_diff2[y];
}

double FastMathDClass::FastExp2(double d) const {
  assert(fabs(d) <= 1023);
  const double g = d + (1023 + (1 << 11));
  const int64_t x = absl::bit_cast<int64_t>(g);
  const int32_t x_low = x;
  const int32_t x_high = x >> 32;

  return absl::bit_cast<double>((x & uint64_t{0x000FFE0000000000}) << 11) *
         cache_.exp2[(x_high >> (9 - kBits)) & kMask1] *
         ((((x_low >> (10 - kBits)) & ((1 << (22 + kBits)) - 1)) |
           ((x_high & ((1 << (9 - kBits)) - 1)) << (22 + kBits))) *
              cache_.magic +
          1.0);
}

